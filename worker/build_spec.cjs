// Writes worker/src/spec.generated.js: the reader prompt, the analyst prompt base and the tool
// definitions, generated from site/js/ai.js so the Worker and the page cannot drift apart.
// Run after changing ai.js or the data:  node worker/build_spec.cjs   (tests check it is up to date)
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
global.TES_ENGINE = require(path.join(root, "site/js/engine.js"));
const AI = require(path.join(root, "site/js/ai.js"));
const L = (f) => JSON.parse(fs.readFileSync(path.join(root, f)));
const meta = L("site/data/meta.json"), current = L("site/data/current_us.json"), gdp = L("site/data/gdp.json");
const data = Object.fromEntries(meta.years.map((y) => [y, L(`site/data/usa_${y}.json`)]));
const NICE = JSON.parse(fs.readFileSync(path.join(root, "site/js/names.json")));
const ctx = { data: (y) => data[y], gdp: (y) => gdp[String(y)], current, years: meta.years, defaultYear: meta.default_year,
  name: (iso) => NICE[iso] || data[meta.default_year].names[iso] || iso, chName: (c) => meta.chapters[c].short, elasticity: () => 0.76 };
function build() {
  const spec = AI.workerSpec(ctx);
  return "// GENERATED by worker/build_spec.cjs from site/js/ai.js. Do not edit by hand.\nexport const SPEC = " + JSON.stringify(spec, null, 1) + ";\n";
}
module.exports = { build, ctx };
if (require.main === module) { fs.writeFileSync(path.join(__dirname, "src/spec.generated.js"), build()); console.log("wrote worker/src/spec.generated.js"); }
